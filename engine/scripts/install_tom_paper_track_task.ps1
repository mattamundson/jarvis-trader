#Requires -Version 5.1
<#
.SYNOPSIS
  Install the daily turn-of-month (TOM) DARK forward paper-track scheduled task.

.DESCRIPTION
  Registers 'Jarvis-TomPaperTrack' to run engine/backtest/tom_paper_track.py once per
  day after the US equity close. The track is OBSERVE-ONLY: it pulls fresh SPY daily
  closes (free via yfinance), records realized turn-of-month close-to-close returns into
  an ISOLATED JSONL ledger under engine/data/tom_paper_track/, and routes NO orders,
  touches NO live DB / position / pipeline. Only TOM days strictly AFTER the pre-
  registered inception date count as forward observations; the run is idempotent (a date
  already recorded is never double-counted), so an occasional double-fire is harmless.

  Goal: accumulate a clean out-of-sample FORWARD record for the pre-registered
  tom_spy_v1 candidate (decision_registry.json) so it can eventually satisfy the
  paper_shadow_passed promotion pillar. The backtest established the prior on SPY
  1993-2026 (Sharpe ~0.79 net@2bps); the forward record tests persistence post-inception.

  Code-path resolution (survives the family-fdr -> main merge): the launcher prefers the
  _spread_track bridge worktree (which carries the merged family-fdr module today, since
  the main checkout is still on a peer branch) and falls back to the MAIN-checkout module
  once family-fdr lands there. The durable ledger always lives in the MAIN checkout's data
  dir, so it persists across worktree pruning regardless of which code path ran.

  Machine-convention compliance (see ~/.claude/rules/windows-pitfalls.md):
    - Battery gate cleared (AllowStartIfOnBatteries + DontStopIfGoingOnBatteries).
    - Hidden wscript+VBS launcher (window style 0) -- WindowStyle Hidden does not reliably
      suppress a console exe popup on this box. VBS propagates python's exit code.
    - ASCII-only source (PS 5.1 mis-parses non-ASCII).
    - LIMITED run level, Interactive logon (S4U throws 0x80070005 on Win11 Home).

  Installs the definition only; does not run the track. Idempotent. Use -Remove to uninstall.

.EXAMPLE
  pwsh -NoProfile -File engine\scripts\install_tom_paper_track_task.ps1
.EXAMPLE
  pwsh -NoProfile -File engine\scripts\install_tom_paper_track_task.ps1 -Remove
#>
[CmdletBinding()]
param(
    [switch]$Remove,
    [string]$AtTime = '5:00PM'
)

$ErrorActionPreference = 'Stop'

$TaskName    = 'Jarvis-TomPaperTrack'
$MainEngine  = 'C:\Users\mattm\ThinkorSwim\jarvis-trader\engine'
$BridgeEngine = 'C:\Users\mattm\ThinkorSwim\_spread_track\engine'
$Python      = Join-Path $MainEngine '.venv\Scripts\python.exe'
$LauncherDir = 'C:\Users\mattm\scripts\hidden-launchers'
$Vbs         = Join-Path $LauncherDir 'jarvis-tom-paper-track.vbs'

if ($Remove) {
    if (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue) {
        Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
        Write-Host "Removed scheduled task $TaskName"
    } else {
        Write-Host "Scheduled task $TaskName is not present; nothing to remove"
    }
    if (Test-Path $Vbs) { Remove-Item $Vbs -Force; Write-Host "Removed launcher $Vbs" }
    return
}

if (-not (Test-Path $Python)) { throw "engine venv python not found: $Python" }
$bridgeMod = Join-Path $BridgeEngine 'backtest\tom_paper_track.py'
$mainMod   = Join-Path $MainEngine   'backtest\tom_paper_track.py'
if (-not (Test-Path $bridgeMod) -and -not (Test-Path $mainMod)) {
    throw "tom_paper_track.py not found in bridge ($bridgeMod) or main ($mainMod)"
}
if (-not (Test-Path $LauncherDir)) {
    New-Item -ItemType Directory -Force -Path $LauncherDir | Out-Null
}

# Hidden launcher: prefer the _spread_track bridge worktree (carries the merged module
# today), fall back to the main-checkout module once family-fdr lands there. Sets CWD to
# the chosen engine dir so `-m backtest.tom_paper_track` imports from it; always uses the
# main engine venv python. wait=True so the exit code reaches the task.
$vbsLines = @(
    "' Auto-generated by install_tom_paper_track_task.ps1 -- daily turn-of-month dark track (hidden).",
    "Set fso = CreateObject(""Scripting.FileSystemObject"")",
    "Set sh = CreateObject(""WScript.Shell"")",
    "bridgeMod = ""$bridgeMod""",
    "mainMod = ""$mainMod""",
    "If fso.FileExists(bridgeMod) Then",
    "  engineDir = ""$BridgeEngine""",
    "ElseIf fso.FileExists(mainMod) Then",
    "  engineDir = ""$MainEngine""",
    "Else",
    "  engineDir = ""$MainEngine""",
    "End If",
    "sh.CurrentDirectory = engineDir",
    "code = sh.Run(""""""$Python"""" -W ignore -m backtest.tom_paper_track"", 0, True)",
    "WScript.Quit(code)"
)
Set-Content -Path $Vbs -Value $vbsLines -Encoding ASCII
Write-Host "Wrote hidden launcher: $Vbs"

$action  = New-ScheduledTaskAction -Execute 'wscript.exe' -Argument ('"{0}"' -f $Vbs)
$trigger = New-ScheduledTaskTrigger -Daily -At $AtTime
$settings = New-ScheduledTaskSettingsSet `
    -AllowStartIfOnBatteries `
    -DontStopIfGoingOnBatteries `
    -StartWhenAvailable `
    -ExecutionTimeLimit (New-TimeSpan -Minutes 5) `
    -MultipleInstances IgnoreNew
$principal = New-ScheduledTaskPrincipal -UserId $env:USERNAME -LogonType Interactive -RunLevel Limited

if (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue) {
    Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
}
Register-ScheduledTask `
    -TaskName $TaskName `
    -Action $action `
    -Trigger $trigger `
    -Settings $settings `
    -Principal $principal `
    -Description 'Daily turn-of-month DARK forward paper track (observe-only; pulls SPY daily closes, records realized TOM returns to engine/data/tom_paper_track/, no orders/no live DB). Feeds the pre-registered tom_spy_v1 graduation candidate.' | Out-Null

Write-Host "Registered $TaskName (daily at $AtTime, hidden, observe-only)."
Get-ScheduledTask -TaskName $TaskName | Get-ScheduledTaskInfo |
    Format-List TaskName, NextRunTime, LastTaskResult, LastRunTime
