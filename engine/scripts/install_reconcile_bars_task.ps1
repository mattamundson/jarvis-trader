#Requires -Version 5.1
<#
.SYNOPSIS
  Install the nightly B4 bar-reconciliation scheduled task (task #27 wiring).

.DESCRIPTION
  Registers 'Jarvis-BarReconcile' to run engine/scripts/reconcile_bars.py --alert
  once nightly. The reconcile compares each symbol's cache CSV vs market_data_bars
  (SQLite) and pushes a Telegram/Discord alert ONLY when it finds a real
  divergence; a clean run is silent. The roll-aware classifier (merged from
  fix/bars-bypass-guard-test) treats uniform roll-basis offsets as BASIS, not
  corruption, so benign contract rolls do not page.

  Severity mapping (from reconcile_bars.py):
    - cache-sourced row diverges > CACHE_TOL (0.05%)  -> trust-breach finding
    - live-sourced row diverges grossly (> LIVE_TOL 5%) -> contamination finding
    - cache bars missing from SQLite > MISSING_WARN_FRAC -> backfill-drift finding
    - uniform roll-basis offset                          -> BASIS, NOT flagged

  Machine-convention compliance (see ~/.claude/rules/windows-pitfalls.md):
    - Battery gate cleared (AllowStartIfOnBatteries + DontStopIfGoingOnBatteries)
      so a catch-up run on battery is not refused with 0x800710E0.
    - Runs via a generated wscript+VBS hidden launcher (window style 0) because
      -WindowStyle Hidden / Settings.Hidden do NOT reliably suppress a console
      popup for a console exe on this box. The VBS waits and propagates python's
      exit code so LastTaskResult stays meaningful.
    - ASCII-only source (PS 5.1 mis-parses non-ASCII).
    - LIMITED run level, Interactive logon (S4U throws 0x80070005 on Win11 Home).

  This script only INSTALLS the task definition; it does not run the reconcile.
  Idempotent: re-running re-registers cleanly. Use -Remove to uninstall.

.EXAMPLE
  pwsh -NoProfile -File engine\scripts\install_reconcile_bars_task.ps1
.EXAMPLE
  pwsh -NoProfile -File engine\scripts\install_reconcile_bars_task.ps1 -Remove
#>
[CmdletBinding()]
param(
    [switch]$Remove,
    [string]$At = '23:50'
)

$ErrorActionPreference = 'Stop'

$TaskName    = 'Jarvis-BarReconcile'
$EngineDir   = 'C:\Users\mattm\ThinkorSwim\jarvis-trader\engine'
$Python      = Join-Path $EngineDir '.venv\Scripts\python.exe'
$LauncherDir = 'C:\Users\mattm\scripts\hidden-launchers'
$Vbs         = Join-Path $LauncherDir 'jarvis-bar-reconcile.vbs'

if ($Remove) {
    if (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue) {
        Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
        Write-Host "Removed scheduled task $TaskName"
    } else {
        Write-Host "Scheduled task $TaskName is not present; nothing to remove"
    }
    if (Test-Path $Vbs) { Remove-Item $Vbs -Force; Write-Host "Removed launcher $Vbs" }
    return
}

if (-not (Test-Path $Python)) { throw "engine venv python not found: $Python" }
if (-not (Test-Path (Join-Path $EngineDir 'scripts\reconcile_bars.py'))) {
    throw "reconcile_bars.py not found under $EngineDir\scripts"
}
if (-not (Test-Path $LauncherDir)) {
    New-Item -ItemType Directory -Force -Path $LauncherDir | Out-Null
}

# Hidden launcher: window style 0 (hidden), wait=True so python's exit code
# propagates to the task via WScript.Quit. Generated, not committed.
$vbsLines = @(
    "' Auto-generated by install_reconcile_bars_task.ps1 -- runs nightly bar reconcile hidden.",
    "Set sh = CreateObject(""WScript.Shell"")",
    "sh.CurrentDirectory = ""$EngineDir""",
    "code = sh.Run(""""""$Python"""" scripts\reconcile_bars.py --alert"", 0, True)",
    "WScript.Quit(code)"
)
Set-Content -Path $Vbs -Value $vbsLines -Encoding ASCII
Write-Host "Wrote hidden launcher: $Vbs"

$action  = New-ScheduledTaskAction -Execute 'wscript.exe' -Argument ('"{0}"' -f $Vbs)
$trigger = New-ScheduledTaskTrigger -Daily -At $At
$settings = New-ScheduledTaskSettingsSet `
    -AllowStartIfOnBatteries `
    -DontStopIfGoingOnBatteries `
    -StartWhenAvailable `
    -ExecutionTimeLimit (New-TimeSpan -Minutes 10) `
    -MultipleInstances IgnoreNew
$principal = New-ScheduledTaskPrincipal -UserId $env:USERNAME -LogonType Interactive -RunLevel Limited

if (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue) {
    Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
}
Register-ScheduledTask `
    -TaskName $TaskName `
    -Action $action `
    -Trigger $trigger `
    -Settings $settings `
    -Principal $principal `
    -Description 'B4 nightly cache-vs-SQLite bar reconciliation; alerts TG/Discord only if a real divergence is found (roll-basis offsets are not flagged).' | Out-Null

Write-Host "Registered $TaskName (daily $At, hidden, alert-only)."
Get-ScheduledTask -TaskName $TaskName | Get-ScheduledTaskInfo |
    Format-List TaskName, NextRunTime, LastTaskResult, LastRunTime
