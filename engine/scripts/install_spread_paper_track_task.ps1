#Requires -Version 5.1
<#
.SYNOPSIS
  Install the hourly ES-NQ spread DARK forward paper-track scheduled task.

.DESCRIPTION
  Registers 'Jarvis-SpreadPaperTrack' to run engine/backtest/spread_paper_track.py
  once per hour. The track is OBSERVE-ONLY: it pulls fresh MES+MNQ 1h bars from the
  engine's read-only /analyze/bars endpoint, computes the spread z-score with the same
  pure functions as the backtest, and records what the ES-NQ spread mean-reversion
  strategy WOULD do into an ISOLATED JSONL ledger under
  engine/data/spread_paper_track/. It routes NO orders, touches NO live DB / position /
  pipeline. Goal: accumulate a clean out-of-sample forward record to test whether the
  backtest's non-stationary (back-loaded) edge persists -- see data/spread_es_nq_results.md.

  The track is idempotent within an hour (skips a bar timestamp it already processed),
  so an hourly trigger that occasionally double-fires is harmless.

  Code-path resolution (survives the eventual worktree -> main merge): the launcher
  prefers the MAIN-checkout module and falls back to the build worktree if main does not
  yet have it. The durable ledger always lives in the MAIN checkout's data dir, so it
  persists across worktree pruning regardless of which code path ran.

  Machine-convention compliance (see ~/.claude/rules/windows-pitfalls.md):
    - Battery gate cleared (AllowStartIfOnBatteries + DontStopIfGoingOnBatteries).
    - Hidden wscript+VBS launcher (window style 0) -- WindowStyle Hidden does not
      reliably suppress a console exe popup on this box. VBS propagates python's exit code.
    - ASCII-only source (PS 5.1 mis-parses non-ASCII).
    - LIMITED run level, Interactive logon (S4U throws 0x80070005 on Win11 Home).

  Installs the definition only; does not run the track. Idempotent. Use -Remove to uninstall.

.EXAMPLE
  pwsh -NoProfile -File engine\scripts\install_spread_paper_track_task.ps1
.EXAMPLE
  pwsh -NoProfile -File engine\scripts\install_spread_paper_track_task.ps1 -Remove
#>
[CmdletBinding()]
param(
    [switch]$Remove,
    [int]$IntervalHours = 1
)

$ErrorActionPreference = 'Stop'

$TaskName    = 'Jarvis-SpreadPaperTrack'
$MainEngine  = 'C:\Users\mattm\ThinkorSwim\jarvis-trader\engine'
$WtEngine    = 'C:\Users\mattm\ThinkorSwim\jarvis-trader\.claude\worktrees\verify-before-build-0624\engine'
$Python      = Join-Path $MainEngine '.venv\Scripts\python.exe'
$LauncherDir = 'C:\Users\mattm\scripts\hidden-launchers'
$Vbs         = Join-Path $LauncherDir 'jarvis-spread-paper-track.vbs'

if ($Remove) {
    if (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue) {
        Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
        Write-Host "Removed scheduled task $TaskName"
    } else {
        Write-Host "Scheduled task $TaskName is not present; nothing to remove"
    }
    if (Test-Path $Vbs) { Remove-Item $Vbs -Force; Write-Host "Removed launcher $Vbs" }
    return
}

if (-not (Test-Path $Python)) { throw "engine venv python not found: $Python" }
$mainMod = Join-Path $MainEngine 'backtest\spread_paper_track.py'
$wtMod   = Join-Path $WtEngine   'backtest\spread_paper_track.py'
if (-not (Test-Path $mainMod) -and -not (Test-Path $wtMod)) {
    throw "spread_paper_track.py not found in main ($mainMod) or worktree ($wtMod)"
}
if (-not (Test-Path $LauncherDir)) {
    New-Item -ItemType Directory -Force -Path $LauncherDir | Out-Null
}

# Hidden launcher: prefer the main-checkout module, fall back to the build worktree.
# Sets CWD to the chosen engine dir so `-m backtest.spread_paper_track` imports from it;
# always uses the main engine venv python. wait=True so the exit code reaches the task.
$vbsLines = @(
    "' Auto-generated by install_spread_paper_track_task.ps1 -- hourly ES-NQ spread dark track (hidden).",
    "Set fso = CreateObject(""Scripting.FileSystemObject"")",
    "Set sh = CreateObject(""WScript.Shell"")",
    "mainMod = ""$mainMod""",
    "If fso.FileExists(mainMod) Then",
    "  engineDir = ""$MainEngine""",
    "Else",
    "  engineDir = ""$WtEngine""",
    "End If",
    "sh.CurrentDirectory = engineDir",
    "code = sh.Run(""""""$Python"""" -W ignore -m backtest.spread_paper_track"", 0, True)",
    "WScript.Quit(code)"
)
Set-Content -Path $Vbs -Value $vbsLines -Encoding ASCII
Write-Host "Wrote hidden launcher: $Vbs"

$action  = New-ScheduledTaskAction -Execute 'wscript.exe' -Argument ('"{0}"' -f $Vbs)
$base    = (Get-Date).Date.AddMinutes(5)
$trigger = New-ScheduledTaskTrigger -Once -At $base -RepetitionInterval (New-TimeSpan -Hours $IntervalHours)
$settings = New-ScheduledTaskSettingsSet `
    -AllowStartIfOnBatteries `
    -DontStopIfGoingOnBatteries `
    -StartWhenAvailable `
    -ExecutionTimeLimit (New-TimeSpan -Minutes 5) `
    -MultipleInstances IgnoreNew
$principal = New-ScheduledTaskPrincipal -UserId $env:USERNAME -LogonType Interactive -RunLevel Limited

if (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue) {
    Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
}
Register-ScheduledTask `
    -TaskName $TaskName `
    -Action $action `
    -Trigger $trigger `
    -Settings $settings `
    -Principal $principal `
    -Description 'Hourly ES-NQ spread DARK forward paper track (observe-only; pulls MES+MNQ bars, records hypothetical spread trades to engine/data/spread_paper_track/, no orders/no live DB).' | Out-Null

Write-Host "Registered $TaskName (every $IntervalHours h, hidden, observe-only)."
Get-ScheduledTask -TaskName $TaskName | Get-ScheduledTaskInfo |
    Format-List TaskName, NextRunTime, LastTaskResult, LastRunTime
