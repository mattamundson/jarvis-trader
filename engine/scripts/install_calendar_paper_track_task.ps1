#Requires -Version 5.1
<#
.SYNOPSIS
  Install the daily calendar-seasonals DARK forward paper-track scheduled task.

.DESCRIPTION
  Registers 'Jarvis-CalendarPaperTrack' to run engine/backtest/calendar_paper_track.py
  once per day after the US equity close. OBSERVE-ONLY: pulls fresh free daily closes
  (yfinance) for each registered (symbol, effect) sleeve, records realized held-day
  close-to-close returns into ISOLATED JSONL ledgers under
  engine/data/calendar_paper_track/<symbol>__<effect>/, and routes NO orders, touches NO
  live DB / position / pipeline. Only held days strictly AFTER each sleeve's inception
  count as forward observations; the run is idempotent.

  Goal: accumulate clean out-of-sample FORWARD records for the 9 calendar gate-v2 PASSers
  (GLD/HYG pre_holiday, LQD/TLT last_day_of_month, SPY/DIA/EEM/EFA santa_claus -- SPY
  pre_holiday is already shadowed by Jarvis-PreHolidayPaperTrack). The screener established
  the priors in-sample (204-cell board); the forward record tests persistence.

  Code-path resolution: the calendar_paper_track module currently lives only on the
  feat/free-daily-export branch (the jt-free-daily worktree). The launcher prefers the
  _spread_track bridge (so once the module lands on master it auto-switches to the stable
  worktree), then the jt-free-daily worktree (where it lives today), then the main checkout.
  The durable ledgers always live in the MAIN checkout's data dir, so they persist across
  worktree pruning regardless of which code path ran.
  NOTE: until calendar_paper_track.py lands on master, do NOT prune the jt-free-daily
  worktree -- it is the only code path that has the module.

  Machine-convention compliance (see ~/.claude/rules/windows-pitfalls.md):
    - Battery gate cleared (AllowStartIfOnBatteries + DontStopIfGoingOnBatteries).
    - Hidden wscript+VBS launcher (window style 0); VBS propagates python's exit code.
    - ASCII-only source (PS 5.1 mis-parses non-ASCII).
    - LIMITED run level, Interactive logon (S4U throws 0x80070005 on Win11 Home).

  Installs the definition only; does not run the track. Idempotent. Use -Remove to uninstall.

.EXAMPLE
  pwsh -NoProfile -File engine\scripts\install_calendar_paper_track_task.ps1
.EXAMPLE
  pwsh -NoProfile -File engine\scripts\install_calendar_paper_track_task.ps1 -Remove
#>
[CmdletBinding()]
param(
    [switch]$Remove,
    [string]$AtTime = '5:20PM'
)

$ErrorActionPreference = 'Stop'

$TaskName         = 'Jarvis-CalendarPaperTrack'
$MainEngine       = 'C:\Users\mattm\ThinkorSwim\jarvis-trader\engine'
$BridgeEngine     = 'C:\Users\mattm\ThinkorSwim\_spread_track\engine'
$FreeDailyEngine  = 'C:\Users\mattm\ThinkorSwim\jt-free-daily\engine'
$Python           = Join-Path $MainEngine '.venv\Scripts\python.exe'
$LauncherDir      = 'C:\Users\mattm\scripts\hidden-launchers'
$Vbs              = Join-Path $LauncherDir 'jarvis-calendar-paper-track.vbs'

if ($Remove) {
    if (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue) {
        Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
        Write-Host "Removed scheduled task $TaskName"
    } else {
        Write-Host "Scheduled task $TaskName is not present; nothing to remove"
    }
    if (Test-Path $Vbs) { Remove-Item $Vbs -Force; Write-Host "Removed launcher $Vbs" }
    return
}

if (-not (Test-Path $Python)) { throw "engine venv python not found: $Python" }
$bridgeMod   = Join-Path $BridgeEngine    'backtest\calendar_paper_track.py'
$freeMod     = Join-Path $FreeDailyEngine 'backtest\calendar_paper_track.py'
$mainMod     = Join-Path $MainEngine      'backtest\calendar_paper_track.py'
if (-not (Test-Path $bridgeMod) -and -not (Test-Path $freeMod) -and -not (Test-Path $mainMod)) {
    throw "calendar_paper_track.py not found in bridge ($bridgeMod), jt-free-daily ($freeMod), or main ($mainMod)"
}
if (-not (Test-Path $LauncherDir)) {
    New-Item -ItemType Directory -Force -Path $LauncherDir | Out-Null
}

# Hidden launcher: prefer the _spread_track bridge (stable, picks up the module once it
# lands on master), then the jt-free-daily worktree (where it lives today), then main.
# Sets CWD to the chosen engine dir so `-m backtest.calendar_paper_track` imports from it;
# always uses the main engine venv python. wait=True so the exit code reaches the task.
$vbsLines = @(
    "' Auto-generated by install_calendar_paper_track_task.ps1 -- daily calendar dark track (hidden).",
    "Set fso = CreateObject(""Scripting.FileSystemObject"")",
    "Set sh = CreateObject(""WScript.Shell"")",
    "bridgeMod = ""$bridgeMod""",
    "freeMod = ""$freeMod""",
    "mainMod = ""$mainMod""",
    "If fso.FileExists(bridgeMod) Then",
    "  engineDir = ""$BridgeEngine""",
    "ElseIf fso.FileExists(freeMod) Then",
    "  engineDir = ""$FreeDailyEngine""",
    "ElseIf fso.FileExists(mainMod) Then",
    "  engineDir = ""$MainEngine""",
    "Else",
    "  engineDir = ""$MainEngine""",
    "End If",
    "sh.CurrentDirectory = engineDir",
    "code = sh.Run(""""""$Python"""" -W ignore -m backtest.calendar_paper_track"", 0, True)",
    "WScript.Quit(code)"
)
Set-Content -Path $Vbs -Value $vbsLines -Encoding ASCII
Write-Host "Wrote hidden launcher: $Vbs"

$action  = New-ScheduledTaskAction -Execute 'wscript.exe' -Argument ('"{0}"' -f $Vbs)
$trigger = New-ScheduledTaskTrigger -Daily -At $AtTime
$settings = New-ScheduledTaskSettingsSet `
    -AllowStartIfOnBatteries `
    -DontStopIfGoingOnBatteries `
    -StartWhenAvailable `
    -ExecutionTimeLimit (New-TimeSpan -Minutes 5) `
    -MultipleInstances IgnoreNew
$principal = New-ScheduledTaskPrincipal -UserId $env:USERNAME -LogonType Interactive -RunLevel Limited

if (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue) {
    Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false
}
Register-ScheduledTask `
    -TaskName $TaskName `
    -Action $action `
    -Trigger $trigger `
    -Settings $settings `
    -Principal $principal `
    -Description 'Daily calendar-seasonals DARK forward paper track (observe-only; pulls free daily closes for 9 gate-PASS sleeves, records realized held-day returns to engine/data/calendar_paper_track/, no orders/no live DB).' | Out-Null

Write-Host "Registered $TaskName (daily at $AtTime, hidden, observe-only)."
Get-ScheduledTask -TaskName $TaskName | Get-ScheduledTaskInfo |
    Format-List TaskName, NextRunTime, LastTaskResult, LastRunTime
