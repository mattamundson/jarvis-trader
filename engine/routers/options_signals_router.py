"""
JARVIS TRADER — Options implied-signals router
===============================================
Serves the SPY/QQQ market-implied snapshot that
``engine/scripts/options_signals_snapshot.py`` writes to
``engine/data/options_signals/latest.json`` — the read surface for the
/signals dashboard page's Options section.

Prefix is ``/options-signals`` because ``/options`` is owned by the (disabled)
options automation module's router. Staleness is self-reported by the payload
(``generated_at`` + ``stale_after_s``), not computed here — the dashboard owns
the LIVE/STALE presentation.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path

from fastapi import APIRouter, HTTPException

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/options-signals", tags=["options-signals"])

_ROUTERS_DIR = Path(__file__).resolve().parent
_ENGINE_DIR = _ROUTERS_DIR.parent
_DATA_DIR = _ENGINE_DIR / "data" / "options_signals"


@router.get("/latest")
async def get_latest_options_signals():
    """Return the most recent options-implied snapshot, verbatim."""
    return _read_latest_snapshot()


@router.get("/opportunity-board")
async def get_options_opportunity_board():
    """Return latest analysis-only defined-risk opportunity boards.

    The boards are generated by ``analysis.options_opportunity_board`` during
    snapshot construction and stored under each symbol horizon. This endpoint is
    a read-only projection over ``latest.json``; it never fetches live quotes or
    routes orders.
    """
    snapshot = _read_latest_snapshot()
    boards: dict[str, dict] = {}
    for symbol, block in (snapshot.get("symbols") or {}).items():
        if not block:
            boards[symbol] = {
                "symbol": symbol,
                "status": "degraded",
                "candidates": [],
                "reject_summary": ["symbol block unavailable"],
            }
            continue
        horizons = block.get("horizons") or []
        nearest = next((h for h in horizons if h.get("label") == "nearest"), horizons[0] if horizons else None)
        board = (nearest or {}).get("opportunity_board")
        if board is None:
            board = {
                "symbol": symbol,
                "status": "degraded",
                "candidates": [],
                "reject_summary": ["opportunity_board missing from snapshot; regenerate latest.json"],
            }
        boards[symbol] = board
    return {
        "schema_version": 1,
        "generated_at": snapshot.get("generated_at"),
        "quote_ts": snapshot.get("quote_ts"),
        "data_delayed_minutes": snapshot.get("data_delayed_minutes"),
        "data_quality": snapshot.get("data_quality"),
        "boards": boards,
        "disclaimer": "Analysis-only defined-risk opportunity board from delayed options quotes; not a trade signal.",
    }


def _read_latest_snapshot() -> dict:
    """Return the most recent options-implied snapshot, or raise HTTPException."""
    path = _DATA_DIR / "latest.json"
    if not path.exists():
        raise HTTPException(status_code=404, detail="no options signals snapshot generated yet")
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        logger.error("options signals snapshot corrupt: %s", exc)
        raise HTTPException(status_code=500, detail="snapshot file corrupt") from exc
