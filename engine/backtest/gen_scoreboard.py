def _fmt(val, fmt=".4f") -> str:
    if val is None:
        return "—"
    try:
        return format(float(val), fmt)
    except (TypeError, ValueError):
        return str(val)


def _champion_summary(d: dict) -> str:
    cp = d.get("champion_params")
    if not cp or not isinstance(cp, dict):
        return "—"
    parts = []
    if "fast" in cp and "slow" in cp:
        parts.append(f"SMA {cp['fast']}/{cp['slow']}")
    if "atr_trail_mult" in cp:
        parts.append(f"trail={cp['atr_trail_mult']}")
    if "min_rv_annualized" in cp and cp["min_rv_annualized"]:
        parts.append(f"rv≥{cp['min_rv_annualized']:.0f}%")
    if "htf_rsi_period" in cp and cp["htf_rsi_period"]:
        parts.append(f"htf_rsi={cp['htf_rsi_period']}")
    if "bb_period" in cp:
        parts.append(f"BB({cp['bb_period']},{cp.get('bb_std', 2.0)})")
    return " | ".join(parts) if parts else str(cp)


def _verdict_badge(v: str, via: str | None) -> str:
    if v == "PASS" and via == "core":
        return "✅ PASS-core"
    if v == "PASS" and via == "alt":
        return "⚡ PASS-alt"
    if v == "PASS":
        return "✅ PASS"
    return "❌ FAIL"


def generate() -> str:
    files = sorted(verdicts_dir.glob("*.json"))
    if not files:
        return "No verdict files found in engine/data/gate_v2_verdicts/\n"

    rows = []
    for f in files:
        d = _load_verdict(f)
        if not d:
            continue

        symbol = d.get("symbol", "?")
        family = d.get("family", "?")
        rank = d.get("rank", "?")
        verdict = d.get("verdict", "?")
        passed_via = d.get("passed_via")

        m = d.get("gate_v2_metrics", {}) or {}
        wfo = d.get("wfo_config", {}) or {}

        pf_ci = _fmt(m.get("pf_ci_lower"))
        p_edge = _fmt(m.get("p_edge"))
        dd_pct = _fmt(m.get("mc_95th_dd_pct"), ".2f")
        dsr = _fmt(m.get("dsr"), ".3f")
        wfo_cons = m.get("wfo_consistency") or "—"
        n_oos = wfo.get("total_oos_trades")
        n_oos_str = str(n_oos) if n_oos is not None else "—"
        n_win = wfo.get("n_oos_windows_with_trades")
        n_win_total = wfo.get("n_windows") or wfo.get("n_oos_windows", "?")
        win_str = f"{n_win}/{n_win_total}" if n_win is not None else "—"

        champ = _champion_summary(d)
        created = (d.get("created_at") or "")[:10]

        rows.append(
            {
                "file": f.name,
                "symbol": symbol,
                "family": family,
                "rank": rank,
                "verdict_badge": _verdict_badge(verdict, passed_via),
                "pf_ci": pf_ci,
                "p_edge": p_edge,
                "dd_pct": dd_pct,
                "dsr": dsr,
                "wfo_cons": wfo_cons,
                "n_oos": n_oos_str,
                "windows": win_str,
                "champion": champ,
                "created": created,
            }
        )

    # Sort: PASS first (core > alt > fail), then by symbol
    _order = {"✅ PASS-core": 0, "⚡ PASS-alt": 1, "✅ PASS": 2, "❌ FAIL": 3}
    rows.sort(key=lambda r: (_order.get(r["verdict_badge"], 9), r["symbol"], r["rank"]))

    now = datetime.now(tz=timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    lines = [
        "# JARVIS TRADER — Strategy Portfolio Scoreboard",
        "",
        f"> Auto-generated by `backtest/gen_scoreboard.py` · Last refresh: {now}",
        ">",
        "> **PASS-core** = all 4 core criteria pass  ",
        "> **PASS-alt** = ALT path ($50K+ account): DSR≥0.30, WFO∈[MOD,STR], fixed_pf≥1.20, cost≥realistic, mc_dd≤4%  ",
        "> **DO NOT TRADE** = engine routing blocks MCL and MNQ regardless of verdict",
        "",
        "## Active Strategies",
        "",
        "| Symbol | Family | Rank | Verdict | PF CI₅ | p_edge | DD₉₅% | DSR | WFO | OOS Trades | Windows | Champion Params | Date |",
        "|--------|--------|------|---------|--------|--------|-------|-----|-----|-----------|---------|----------------|------|",
    ]

    pass_rows = [r for r in rows if "PASS" in r["verdict_badge"]]
    fail_rows = [r for r in rows if "FAIL" in r["verdict_badge"]]

    for r in pass_rows:
        lines.append(
            f"| {r['symbol']} | {r['family']} | {r['rank']} | {r['verdict_badge']} "
            f"| {r['pf_ci']} | {r['p_edge']} | {r['dd_pct']} | {r['dsr']} "
            f"| {r['wfo_cons']} | {r['n_oos']} | {r['windows']} | {r['champion']} | {r['created']} |"
        )

    if fail_rows:
        lines += [
            "",
            "## Failed / Blocked Hypotheses",
            "",
            "| Symbol | Family | Rank | Verdict | File | Date |",
            "|--------|--------|------|---------|------|------|",
        ]
        for r in fail_rows:
            lines.append(
                f"| {r['symbol']} | {r['family']} | {r['rank']} "
                f"| {r['verdict_badge']} | `{r['file']}` | {r['created']} |"
            )

    lines += [
        "",
        "## Thresholds Reference",
        "",
        "| Metric | CORE | ALT |",
        "|--------|------|-----|",
        "| `pf_ci_lower` | ≥ 1.10 | ≥ 1.10 |",
        "| `p_edge` | ≥ 0.95 | — |",
        "| `mc_95th_dd` | ≤ 5% | ≤ 4% |",
        "| `dsr` | ≥ 0.10 | ≥ 0.30 |",
        "| `wfo_consistency` | — | MOD or STR |",
        "| `fixed_params_min_pf` | — | ≥ 1.20 |",
        "| `cost_survives_through` | — | ≥ realistic |",
        "",
        "See `backtest/_gate_v2_helpers.py` for canonical constant definitions.",
        "Run `backtest/test_gate_v2_policy.py` to verify no accidental threshold drift.",
        "",
    ]

    return "\n".join(lines)


def main():
    content = generate()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(content, encoding="utf-8")
    print(f"[scoreboard] Written -> {output_path}")
    # Print with unicode replacement for Windows cp1252 consoles
    print(content.encode("ascii", errors="replace").decode("ascii"))


if __name__ == "__main__":
    sys.path.insert(0, str(engine_root))
    main()
