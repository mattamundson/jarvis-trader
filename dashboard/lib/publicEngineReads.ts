export function isPublicEngineRead(pathname: string): boolean {
  return ENGINE_READ_ROUTES.some((route) => {
    const pattern = route
      .split("/")
      .map((part) =>
        part.startsWith("{")
          ? "[A-Za-z0-9_:=.^-]+"
          : part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"),
      )
      .join("/");
    return new RegExp(`^${pattern}/?$`).test(pathname);
  });
}
