"""
Funnel CLI Orchestrator
=======================

Single entry point for running phases of the Jarvis Robust Strategy Funnel.

Usage:
    python -m jarvis_funnel.run --phase 1 --repo C:/path/to/jarvis-trader
    python -m jarvis_funnel.run --phase 2 --instrument ES
    python -m jarvis_funnel.run --phase 3
    python -m jarvis_funnel.run --phase 4
    python -m jarvis_funnel.run --tracker

The orchestrator:
  - Locates the sync root (default: $JARVIS_FUNNEL_SYNC_ROOT or ./funnel-out)
  - Discovers cards, configs, results in standard locations
  - Dispatches to phase1_inventory.py, funnel_gate.py, tracker.py as needed
  - For Phase 2/3/4, generates the per-strategy run configs that point at
    engine/backtest/ primitives in the jarvis-trader repo

Phase 2/3/4 are NOT implemented as backtest runners themselves — they emit
config files and a shell script that drives engine/backtest/run_*.py with
the right parameters. The intent: do not duplicate the existing engine.
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

logger = logging.getLogger("jarvis_funnel.run")

# Default sync root (OneDrive handoff folder)
DEFAULT_SYNC_ROOT_HINT = "C:/Users/matt/OneDrive/jarvis-trader-handoff"


def get_sync_root(arg_value: Path | None) -> Path:
    if arg_value:
        return arg_value
    env = os.environ.get("JARVIS_FUNNEL_SYNC_ROOT")
    if env:
        return Path(env)
    return Path(DEFAULT_SYNC_ROOT_HINT)


# ── Phase 1 dispatcher ───────────────────────────────────────────────────────


def run_phase_1(args) -> int:
    sync_root = get_sync_root(args.sync_root)
    out_path = sync_root / "cards" / "strategies_v1.jsonl"
    bookmarks = args.bookmarks or (sync_root / "bookmarks.html")
    if not bookmarks.exists():
        bookmarks_alt = sync_root / "bookmarks.json"
        if bookmarks_alt.exists():
            bookmarks = bookmarks_alt

    cmd = [
        sys.executable, "-m", "jarvis_funnel.phase1_inventory",
        "--repo", str(args.repo),
        "--out", str(out_path),
    ]
    if bookmarks.exists():
        cmd += ["--bookmarks", str(bookmarks)]
    else:
        logger.warning(f"No bookmarks file found at {bookmarks} — running with repo only")

    logger.info("Phase 1: invoking inventory pipeline")
    logger.info(f"  Command: {' '.join(cmd)}")
    return subprocess.call(cmd)


# ── Phase 2 dispatcher (smoke test config generator) ─────────────────────────


def run_phase_2(args) -> int:
    sync_root = get_sync_root(args.sync_root)
    cards_file = sync_root / "cards" / "strategies_v1.jsonl"
    if not cards_file.exists():
        logger.error(f"No strategies_v1.jsonl at {cards_file} — run Phase 1 first")
        return 1

    out_dir = sync_root / "phase2_configs"
    out_dir.mkdir(parents=True, exist_ok=True)

    # Read cards, filter to those that passed Phase 1
    cards = []
    with cards_file.open("r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                cards.append(json.loads(line))

    eligible = [c for c in cards if c.get("phase_1_status") == "PASSED"]
    logger.info(f"Phase 2: generating configs for {len(eligible)} eligible strategies (of {len(cards)} total)")

    run_script_lines = [
        "#!/usr/bin/env bash",
        "# Auto-generated by jarvis_funnel.run --phase 2",
        "# Runs Phase 2 smoke tests against engine/backtest/ primitives.",
        "set -euo pipefail",
        f"# Generated at {datetime.now(timezone.utc).isoformat()}",
        "",
    ]

    for card in eligible:
        hid = card["hypothesis_id"]
        instrument = args.instrument or card.get("instruments", {}).get("primary") or "ES"
        primary_tf = card.get("timeframes", {}).get("primary") or "5m"

        config = {
            "hypothesis_id": hid,
            "phase": 2,
            "instrument": instrument,
            "timeframe": primary_tf,
            "lookback_months": 24,
            "in_sample_fraction": 0.70,
            "use_author_defaults": True,
            "commission_per_rt": 2.50,
            "slippage_ticks": 1,
            "kill_thresholds": {
                "sharpe_min": 0.50,
                "profit_factor_min": 1.10,
                "max_dd_pct_max": 0.25,
                "min_trades": 20,
            },
            "card_provenance": card.get("provenance"),
        }
        config_path = out_dir / f"{hid}__phase2.json"
        config_path.write_text(json.dumps(config, indent=2), encoding="utf-8")

        # Add a run line — points at the existing engine
        runner_hint = next(
            (s["path"] for s in card.get("provenance", {}).get("repo_sources", [])
             if s.get("role") == "repo_runner"),
            None,
        )
        if runner_hint:
            run_script_lines.append(f"# {hid}")
            run_script_lines.append(f"python {runner_hint} --config {config_path.as_posix()} --out-dir {sync_root.as_posix()}/results/{hid}/phase2 || echo '  FAILED: {hid}'")
        else:
            run_script_lines.append(f"# SKIPPED — no repo runner for {hid}; needs implementation")

    script_path = out_dir / "run_all.sh"
    script_path.write_text("\n".join(run_script_lines), encoding="utf-8")
    logger.info(f"Phase 2: wrote {len(eligible)} configs to {out_dir}/")
    logger.info(f"Phase 2: orchestration script at {script_path}")
    logger.info("Run that shell script (or its Powershell equivalent) on Matt's machine to execute.")
    return 0


# ── Phase 3 dispatcher (robustness battery config) ───────────────────────────


def run_phase_3(args) -> int:
    sync_root = get_sync_root(args.sync_root)
    cards_file = sync_root / "cards" / "strategies_v2.jsonl"
    if not cards_file.exists():
        # Fall back to v1 if v2 doesn't exist yet
        cards_file = sync_root / "cards" / "strategies_v1.jsonl"
    if not cards_file.exists():
        logger.error("No strategy cards file found")
        return 1

    out_dir = sync_root / "phase3_configs"
    out_dir.mkdir(parents=True, exist_ok=True)

    cards = []
    with cards_file.open("r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                cards.append(json.loads(line))

    eligible = [c for c in cards if c.get("phase_2_status") == "PASSED"]
    logger.info(f"Phase 3: generating robustness configs for {len(eligible)} Phase 2 survivors")

    for card in eligible:
        hid = card["hypothesis_id"]
        config = {
            "hypothesis_id": hid,
            "phase": 3,
            "robustness_tests": {
                "walk_forward": {"folds": 10, "anchor": "rolling"},
                "cpcv": {"n_groups": 6, "k_test": 2},
                "deflated_sharpe": {"trial_count_source": "auto"},
                "pbo": {"n_combos": 16},
                "monte_carlo": {"n_resamples": 10000},
                "bar_permutation": {"n_permutations": 1000},
                "regime_conditioning": {"vix_bands": [15, 20, 30]},
                "multi_timeframe": {
                    "test_timeframes": [tf for tf in ["5m", "30m", "1h"] if tf in card.get("timeframes", {}).get("applicable", [])]
                },
                "slippage_stress": {"multipliers": [2.0, 3.0]},
                "cross_instrument": {"test_on": ["MES", "MGC", "MNQ"]},
            },
            "parameter_sensitivity": card.get("parameter_sensitivity_to_test", {}),
        }
        (out_dir / f"{hid}__phase3.json").write_text(json.dumps(config, indent=2), encoding="utf-8")

    logger.info(f"Phase 3: wrote {len(eligible)} configs to {out_dir}/")
    logger.info("After running these against engine/backtest/, run --phase gate to adjudicate.")
    return 0


def run_phase_gate(args) -> int:
    sync_root = get_sync_root(args.sync_root)
    cards_file = sync_root / "cards" / "strategies_v3.jsonl"
    if not cards_file.exists():
        cards_file = sync_root / "cards" / "strategies_v1.jsonl"
    results_dir = sync_root / "results"
    out_dir = sync_root / "verdicts"
    cmd = [
        sys.executable, "-m", "jarvis_funnel.funnel_gate",
        "--cards", str(cards_file),
        "--results-dir", str(results_dir),
        "--out-dir", str(out_dir),
    ]
    return subprocess.call(cmd)


def run_phase_4(args) -> int:
    sync_root = get_sync_root(args.sync_root)
    verdicts_dir = sync_root / "verdicts"
    if not verdicts_dir.exists():
        logger.error("No verdicts/ directory — run --phase gate first")
        return 1

    tier_a = []
    for vf in verdicts_dir.glob("*__verdict.json"):
        data = json.loads(vf.read_text(encoding="utf-8"))
        if data.get("tier") == "A":
            tier_a.append(data["hypothesis_id"])

    logger.info(f"Phase 4: {len(tier_a)} Tier A strategies eligible for combination testing")

    out_dir = sync_root / "phase4_configs"
    out_dir.mkdir(parents=True, exist_ok=True)

    config = {
        "phase": 4,
        "tier_a_strategies": tier_a,
        "max_corr_for_combo": 0.30,
        "combo_sizes": [2, 3],
        "ensemble_modes": ["equal_weight", "vol_target", "vote"],
        "metric_threshold_for_inclusion": {"marginal_sharpe_contribution_min": 0.15},
    }
    (out_dir / "phase4_run_config.json").write_text(json.dumps(config, indent=2), encoding="utf-8")
    logger.info(f"Phase 4 config written to {out_dir}/phase4_run_config.json")
    return 0


def run_tracker_phase(args) -> int:
    sync_root = get_sync_root(args.sync_root)
    cmd = [sys.executable, "-m", "jarvis_funnel.tracker", "--sync-root", str(sync_root)]
    if args.notify:
        cmd.append("--notify")
    return subprocess.call(cmd)


# ── Main ─────────────────────────────────────────────────────────────────────


def main():
    parser = argparse.ArgumentParser(description="Jarvis Robust Strategy Funnel orchestrator")
    parser.add_argument("--phase", choices=["1", "2", "3", "4", "gate"], help="Phase to run")
    parser.add_argument("--tracker", action="store_true", help="Run the weekly tracker instead of a phase")
    parser.add_argument("--repo", type=Path, help="Path to jarvis-trader repo (Phase 1 only)")
    parser.add_argument("--bookmarks", type=Path, help="Bookmarks export path (Phase 1; defaults to sync_root/bookmarks.html)")
    parser.add_argument("--sync-root", type=Path, help=f"OneDrive sync root (default: {DEFAULT_SYNC_ROOT_HINT})")
    parser.add_argument("--instrument", default=None, help="Override primary instrument (e.g. ES)")
    parser.add_argument("--notify", action="store_true", help="Emit notification summary (tracker only)")
    parser.add_argument("--log-level", default="INFO")
    args = parser.parse_args()

    logging.basicConfig(level=args.log_level, format="%(asctime)s %(levelname)s %(name)s: %(message)s")

    if args.tracker:
        return run_tracker_phase(args)

    if args.phase == "1":
        if not args.repo:
            parser.error("--repo is required for Phase 1")
        return run_phase_1(args)
    elif args.phase == "2":
        return run_phase_2(args)
    elif args.phase == "3":
        return run_phase_3(args)
    elif args.phase == "gate":
        return run_phase_gate(args)
    elif args.phase == "4":
        return run_phase_4(args)
    else:
        parser.print_help()
        return 1


if __name__ == "__main__":
    sys.exit(main())
