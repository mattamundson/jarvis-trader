<#
.SYNOPSIS
  jarvis-trader maker/checker loop. A "maker" agent drafts a change for -Task in
  an ISOLATED git worktree, a hardcoded safety guard rejects any diff touching
  safety files, then a "checker" agent adversarially reviews the diff READ-ONLY.
  It STOPS there: it never commits, pushes, opens, or merges a PR.

.DESCRIPTION
  This composes the two halves of the highest-value loop move (split the writer
  from the reviewer) while staying inside the blast-radius discipline:

    1. Isolation     — all maker edits happen in a throwaway worktree on a new
                       branch; your working tree is never touched.
    2. Safety guard  — a HARDCODED path check (not LLM-trusted) aborts if the
                       maker's diff touches engine/risk, config.py, kill-switch,
                       trader sizing, or .env. The maker is also told not to.
    3. Checker       — a separate read-only agent reviews the diff (same
                       discipline as review-loop.ps1 / safety-reviewer).
    4. Human gate    — output is a worktree + a report. YOU inspect, then open a
                       PR by hand if you agree. Nothing is committed for you.

  All loop-brakes apply to both agents (step cap, budget ceiling, permission
  classifier). The maker may Write/Edit (that is its job) but cannot commit/push.

  Exit codes:
    0  GREEN          — change drafted, checker found no blocking issues
    2  RED            — checker found blocking issue(s)
    3  ERROR          — an agent run failed / no parseable status
    4  SAFETY_BLOCK   — maker touched a forbidden safety path; diff rejected

.EXAMPLE
  pwsh -File scripts\loops\maker-checker-loop.ps1 -Task "Add a --dry-run flag to scripts/foo.py and a test"
#>

[CmdletBinding()]
param(
    [Parameter(Mandatory)][string] $Task,
    [string] $BaseBranch   = "master",
    [int]    $MakerTurns   = 60,
    [double] $MakerBudget  = 6.00,
    [int]    $CheckTurns   = 40,
    [double] $CheckBudget  = 4.00,
    [string] $RepoRoot     = (Resolve-Path "$PSScriptRoot\..\..").Path
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

. "$PSScriptRoot\loop-lib.ps1"
$reportDir = Initialize-LoopPaths -RepoRoot $RepoRoot   # report lands in MAIN repo
$stamp     = Get-Date -Format "yyyy-MM-dd_HHmm"
$reportPath = Join-Path $reportDir "maker-checker_$stamp.md"
$loopName  = "maker-checker"

# HARDCODED safety paths (mirror .claude/rules/commits.md). Never LLM-trusted.
$forbidden = 'engine/(risk/|config\.py|execution/kill_switch\.py|agents/trader\.py|\.env)'

$branch       = "loop/maker-$stamp"
$worktreePath = Join-Path $RepoRoot ".worktrees\maker-$stamp"

function Write-Outcome {
    param([string] $Status, [int] $Code, [string] $Note, [string] $Body)
    $header = "# Maker/checker report - $stamp ($Status)`n`n" +
              "Task: $Task`nWorktree: $worktreePath  (branch $branch)`n`n" +
              "_Generated by scripts/loops/maker-checker-loop.ps1. Nothing was committed " +
              "or pushed; inspect the worktree and open a PR by hand if you agree._`n`n"
    Set-Content -Path $reportPath -Value ($header + $Body) -Encoding UTF8
    Write-LoopHeartbeat -LoopName $loopName -Status $Status
    $icon = if ($Status -eq "GREEN") { "[OK]" } else { "[!!]" }
    Send-LoopNotification -Message "$icon jarvis maker/checker $Status - $Note ($stamp)" | Out-Null
    Write-Host "[maker-checker] $Status - report: $reportPath (exit $Code)"
    exit $Code
}

# --- 1. Isolated worktree -----------------------------------------------------
Push-Location $RepoRoot
try {
    git fetch origin $BaseBranch --quiet 2>&1 | Out-Null
    git worktree add -b $branch $worktreePath $BaseBranch 2>&1 | Out-Null
    if ($LASTEXITCODE -ne 0) { Pop-Location; Write-Outcome "ERROR" 3 "worktree create failed" "Could not create worktree on $BaseBranch." }
}
finally { Pop-Location }

# --- 2. Maker (may edit, in the worktree only; cannot commit/push) ------------
$makerPrompt = @"
You are the MAKER. Implement this task in the current working directory only:

TASK: $Task

Rules:
- Make the smallest change that satisfies the task, with a test where practical.
- Do NOT edit any of: engine/risk/, engine/config.py, engine/execution/kill_switch.py,
  engine/agents/trader.py position sizing, engine/.env. If the task seems to require
  it, STOP and explain why instead of editing.
- Do NOT run git commit, git push, or open a PR. Leave changes unstaged.
- End with one line: MAKER_DONE <one-sentence summary of what you changed>.
"@

Write-Host "[maker-checker] maker drafting in $worktreePath ..."
Push-Location $worktreePath
try {
    $makerOut = claude -p --max-turns $MakerTurns --max-budget-usd $MakerBudget `
        --permission-mode auto --disallowedTools "WebFetch" `
        $makerPrompt 2>&1 | Out-String
}
catch { $makerOut = "Maker failed: $($_.Exception.Message)" }
finally { Pop-Location }

# --- 2b. HARDCODED safety guard on the resulting diff -------------------------
Push-Location $worktreePath
try { $changed = (git status --porcelain --untracked-files=all 2>$null) | Out-String }
finally { Pop-Location }

$hits = ($changed -split "`n") | Where-Object { $_ -match $forbidden }
if ($hits) {
    $list = ($hits | ForEach-Object { $_.Trim() }) -join "`n"
    Write-Outcome "SAFETY_BLOCK" 4 "maker touched safety files" `
        "Maker diff touched FORBIDDEN safety paths; rejected without review:`n`n$list`n`nMaker output:`n$makerOut"
}

if ([string]::IsNullOrWhiteSpace($changed)) {
    Write-Outcome "ERROR" 3 "maker produced no changes" "Maker made no file changes.`n`nMaker output:`n$makerOut"
}

# --- 3. Checker (read-only review of the worktree diff) -----------------------
$checkPrompt = @"
You are the CHECKER. Adversarially review the uncommitted changes in this
working directory against $BaseBranch. Assume the author is wrong until proven
otherwise.

1. Inspect:  git diff $BaseBranch  and  git status
2. Report correctness bugs, missing tests, and any safety-invariant risk
   (apply .claude/agents/safety-reviewer.md if any safety-adjacent file is near).
   Cite file:line.

Output:
  ## Blocking issues   (empty if none)
  ## Non-blocking
Then as the VERY LAST line, exactly one of:
  LOOP_STATUS: GREEN
  LOOP_STATUS: RED <n> blocking issues

Do NOT edit, commit, push, or merge anything. Review only.
"@

Write-Host "[maker-checker] checker reviewing ..."
Push-Location $worktreePath
try {
    $checkOut = claude -p --max-turns $CheckTurns --max-budget-usd $CheckBudget `
        --permission-mode auto --tools "Read,Bash,Grep" --disallowedTools "Write,Edit" `
        $checkPrompt 2>&1 | Out-String
}
catch { $checkOut = "Checker failed: $($_.Exception.Message)" }
finally { Pop-Location }

$body = "## Maker`n$makerOut`n`n## Changed files`n$changed`n`n## Checker`n$checkOut"

if ($checkOut -match 'LOOP_STATUS:\s*GREEN') {
    Write-Outcome "GREEN" 0 "drafted, review clean" $body
}
elseif ($checkOut -match 'LOOP_STATUS:\s*RED(.*)') {
    Write-Outcome "RED" 2 ("blocking:" + $Matches[1].Trim()) $body
}
else {
    Write-Outcome "ERROR" 3 "no parseable checker status" $body
}
