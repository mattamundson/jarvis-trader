<#
.SYNOPSIS
  jarvis-trader read-only triage loop. Runs the fast engine test suite and the
  dashboard build via a fully-capped Claude Code headless run, writes a
  timestamped report to docs/loop-reports/, emits a heartbeat, pushes a one-line
  notification, and exits non-zero when there are NEW failures.

.DESCRIPTION
  All "brakes" from the loop-brakes skill are baked in:
    - step cap        (--max-turns)
    - budget ceiling  (--max-budget-usd)
    - tool allowlist  (--tools Read,Bash,Grep ; --disallowedTools Write,Edit)
    - permission mode (auto: classifier reviews, no prompts)
    - blast radius    (agent is read-only; THIS script does the only file write)
    - stop condition  (agent must end with a LOOP_STATUS: GREEN|RED marker)
    - dead-man check  (heartbeat each run; see heartbeat-check.ps1)
    - notification    (best-effort Discord push of the one-line result)

  The agent CANNOT edit files. This script captures the agent's summary on stdout
  and writes the report itself, so curated docs are never touched by the loop.
  Safe for unattended use: never places orders, never touches engine/risk,
  engine/config.py, or kill-switch code.

  Exit codes (so Windows Task Scheduler history shows red/green):
    0  GREEN  — no new failures
    2  RED    — new failures found (notification sent at higher severity)
    3  ERROR  — the agent run itself failed / no parseable status

.NOTES
  Companion to docs/loop-engineering-quickstart.md.
  Set $env:JARVIS_LOOP_WEBHOOK to receive notifications.
#>

[CmdletBinding()]
param(
    [int]    $MaxTurns     = 30,
    [double] $MaxBudgetUsd = 3.00,
    [string] $RepoRoot     = (Resolve-Path "$PSScriptRoot\..\..").Path
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

. "$PSScriptRoot\loop-lib.ps1"
$reportDir = Initialize-LoopPaths -RepoRoot $RepoRoot

$stamp      = Get-Date -Format "yyyy-MM-dd_HHmm"
$reportPath = Join-Path $reportDir "triage_$stamp.md"
$loopName   = "triage"

# --- The prompt: read-only investigation, machine-checkable status line -------
$prompt = @"
Run the jarvis-trader fast checks and report ONLY problems, concisely.

1. Engine fast tests:  cd engine && .venv/Scripts/python -m pytest tests/ -m "not slow"
2. Dashboard build:    cd dashboard && pnpm run build

Output a short markdown report with three sections:
  ## NEW failures   (test name + one-line cause; empty if none)
  ## Build status   (pass/fail; first error if fail)
  ## Notes          (anything that needs a human; empty if none)

Then, as the VERY LAST line, output exactly one of:
  LOOP_STATUS: GREEN
  LOOP_STATUS: RED <n> new failures

Do NOT edit any files. Do NOT run git. Do NOT touch engine/risk, engine/config.py,
or any order/kill-switch code. If a check cannot run, say so and end with
LOOP_STATUS: RED.
"@

Write-Host "[triage-loop] running capped headless agent (max-turns=$MaxTurns, budget=`$$MaxBudgetUsd)..."

Push-Location $RepoRoot
try {
    $summary = claude -p `
        --max-turns $MaxTurns `
        --max-budget-usd $MaxBudgetUsd `
        --permission-mode auto `
        --tools "Read,Bash,Grep" `
        --disallowedTools "Write,Edit" `
        $prompt 2>&1 | Out-String
}
catch {
    $summary = "Agent run failed to complete:`n$($_.Exception.Message)"
}
finally {
    Pop-Location
}

# --- Classify the run from the machine-checkable marker -----------------------
if ($summary -match 'LOOP_STATUS:\s*GREEN') {
    $status = "GREEN"; $exit = 0; $note = "all checks green"
}
elseif ($summary -match 'LOOP_STATUS:\s*RED(.*)') {
    $status = "RED"; $exit = 2; $note = ("failures: " + $Matches[1].Trim())
}
else {
    $status = "ERROR"; $exit = 3; $note = "agent produced no parseable LOOP_STATUS"
}

# --- The script (not the agent) writes the report + heartbeat -----------------
$header = "# Triage report - $stamp ($status)`n`n_Generated by scripts/loops/triage-loop.ps1 (read-only loop)._`n`n"
Set-Content -Path $reportPath -Value ($header + $summary) -Encoding UTF8
Write-LoopHeartbeat -LoopName $loopName -Status $status

# --- Notify (best-effort) -----------------------------------------------------
$icon = if ($status -eq "GREEN") { "[OK]" } else { "[!!]" }
Send-LoopNotification -Message "$icon jarvis triage $status - $note ($stamp)" | Out-Null

Write-Host "[triage-loop] $status - report: $reportPath (exit $exit)"
exit $exit
