<#
.SYNOPSIS
  jarvis-trader review loop (the "checker" half of maker/checker). Runs an
  adversarial, READ-ONLY review of the current branch's diff vs a base ref and
  writes the verdict to docs/loop-reports/. Reuses the repo's existing review
  tooling (the /code-review skill + safety-reviewer discipline) rather than
  reimplementing review logic.

.DESCRIPTION
  This is a Tier-2 loop: higher-touch than triage (it reasons over a diff) but
  still fully capped and incapable of changing anything. The agent runs with
  --disallowedTools "Write,Edit" so it CANNOT modify code, CANNOT commit, CANNOT
  open or merge a PR. Its only output is a review report this script writes.

  All loop-brakes apply: step cap, budget ceiling, read-only tool set, heartbeat,
  notification, and a machine-checkable LOOP_STATUS marker driving the exit code.

  Intended use: run after you (or a "maker" agent) stage work on a branch, to get
  a second, adversarial opinion before you open a PR by hand. It never auto-merges
  and never touches engine/risk, engine/config.py, or kill-switch code.

  Exit codes:
    0  GREEN  — review found no blocking issues
    2  RED    — review found blocking issue(s) (notification sent)
    3  ERROR  — the agent run failed / no parseable status

.EXAMPLE
  pwsh -File scripts\loops\review-loop.ps1 -BaseRef origin/master
#>

[CmdletBinding()]
param(
    [string] $BaseRef      = "origin/master",
    [int]    $MaxTurns     = 40,
    [double] $MaxBudgetUsd = 4.00,
    [string] $RepoRoot     = (Resolve-Path "$PSScriptRoot\..\..").Path
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

. "$PSScriptRoot\loop-lib.ps1"
$reportDir = Initialize-LoopPaths -RepoRoot $RepoRoot
$stamp      = Get-Date -Format "yyyy-MM-dd_HHmm"
$reportPath = Join-Path $reportDir "review_$stamp.md"
$loopName   = "review"

# --- Prompt: adversarial, read-only, reuse existing review tooling ------------
$prompt = @"
You are the CHECKER in a maker/checker loop. Adversarially review the current
working changes against $BaseRef. Assume the author is wrong until the diff
proves otherwise.

1. Determine the diff:  git diff $BaseRef...HEAD  (and `git status` for staged/unstaged)
2. Run the repo's review discipline. If the /code-review skill is available, use
   it. If the diff touches engine/risk/, engine/config.py, safety_layer.py, or
   any kill-switch logic, ALSO apply the safety-reviewer checklist in
   .claude/agents/safety-reviewer.md and verify every hardcoded limit is intact.
3. Report correctness bugs, missing tests, and any safety-invariant risk. Cite
   file:line.

Output a short markdown report:
  ## Blocking issues   (must fix before merge; empty if none)
  ## Non-blocking       (nits / suggestions)
  ## Safety check       (PASS/FAIL + which invariants, or "n/a - no safety files touched")

Then, as the VERY LAST line, output exactly one of:
  LOOP_STATUS: GREEN
  LOOP_STATUS: RED <n> blocking issues

Do NOT edit any files. Do NOT commit, push, open, or merge a PR. Review only.
"@

Write-Host "[review-loop] adversarial review vs $BaseRef (max-turns=$MaxTurns, budget=`$$MaxBudgetUsd)..."

Push-Location $RepoRoot
try {
    $summary = claude -p `
        --max-turns $MaxTurns `
        --max-budget-usd $MaxBudgetUsd `
        --permission-mode auto `
        --tools "Read,Bash,Grep" `
        --disallowedTools "Write,Edit" `
        $prompt 2>&1 | Out-String
}
catch {
    $summary = "Review agent failed to complete:`n$($_.Exception.Message)"
}
finally {
    Pop-Location
}

# --- Classify from the machine-checkable marker ------------------------------
if ($summary -match 'LOOP_STATUS:\s*GREEN') {
    $status = "GREEN"; $exit = 0; $note = "no blocking issues"
}
elseif ($summary -match 'LOOP_STATUS:\s*RED(.*)') {
    $status = "RED"; $exit = 2; $note = ("blocking: " + $Matches[1].Trim())
}
else {
    $status = "ERROR"; $exit = 3; $note = "no parseable LOOP_STATUS"
}

$header = "# Review report - $stamp ($status) vs $BaseRef`n`n_Generated by scripts/loops/review-loop.ps1 (read-only checker)._`n`n"
Set-Content -Path $reportPath -Value ($header + $summary) -Encoding UTF8
Write-LoopHeartbeat -LoopName $loopName -Status $status

$icon = if ($status -eq "GREEN") { "[OK]" } else { "[!!]" }
Send-LoopNotification -Message "$icon jarvis review $status - $note ($stamp)" | Out-Null

Write-Host "[review-loop] $status - report: $reportPath (exit $exit)"
exit $exit
